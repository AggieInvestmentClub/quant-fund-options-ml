def get_period_results(period: str) -> List[Dict[str, Any]]:
    """Return benchmark results list for a given period ('1d', '1w', '1m', '3m', '6m')."""
    if period not in BENCHMARK_STATE:
        raise KeyError(f"Unknown period '{period}'. Choose from {list(BENCHMARK_STATE.keys())}")
    return BENCHMARK_STATE[period]


def get_executive_summary() -> Dict[str, Dict[str, Any]]:
    """Compute executive summary metrics across all periods for each branch."""
    summary: Dict[str, Dict[str, Any]] = {}
    periods = list(BENCHMARK_STATE.keys())
    for b in BENCHMARK_METADATA["branches"]:
        summary[b] = {
            "wall_times": {},
            "cpu_times": {},
            "max_speedup": 1.0,
        }
        speedups = []
        for p in periods:
            p_map = {r["branch"]: r for r in BENCHMARK_STATE[p]}
            base_wall = p_map.get("main", {}).get("total_wall", 0.0)
            b_wall = p_map.get(b, {}).get("total_wall", 0.0)
            b_cpu = p_map.get(b, {}).get("total_cpu", 0.0)
            summary[b]["wall_times"][p] = b_wall
            summary[b]["cpu_times"][p] = b_cpu
            if base_wall > 0 and b_wall > 0:
                speedups.append(base_wall / b_wall)
        summary[b]["max_speedup"] = max(speedups) if speedups else 1.0
    return summary


def print_summary() -> None:
    """Print formatted summary tables to standard output."""
    print("=" * 80)
    print("OPTIONS PIPELINE BENCHMARK RESULTS (ALL BRANCHES)")
    print("=" * 80)
    periods = ["1d", "1w", "1m", "3m", "6m"]
    
    print("\n--- Wall Time Across Periods (seconds) ---")
    header = f"{'Branch':<25} | " + " | ".join(f"{p.upper():>9}" for p in periods) + " | Max Speedup"
    print(header)
    print("-" * len(header))
    summary = get_executive_summary()
    for b in BENCHMARK_METADATA["branches"]:
        vals = [f"{summary[b]['wall_times'].get(p, 0.0):>8.2f}s" for p in periods]
        sp = f"{summary[b]['max_speedup']:.2f}x" if b != "main" else "1.00x (ref)"
        print(f"{b:<25} | " + " | ".join(vals) + f" | {sp:>11}")
        
    print("\n--- CPU Time Across Periods (seconds) ---")
    header = f"{'Branch':<25} | " + " | ".join(f"{p.upper():>9}" for p in periods)
    print(header)
    print("-" * len(header))
    for b in BENCHMARK_METADATA["branches"]:
        vals = [f"{summary[b]['cpu_times'].get(p, 0.0):>8.2f}s" for p in periods]
        print(f"{b:<25} | " + " | ".join(vals))
    print("=" * 80)


if __name__ == "__main__":
    print_summary()
